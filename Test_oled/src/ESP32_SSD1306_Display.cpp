void OLED_Show_Monitoring() {
    static int16_t fill_pos = 0;
    static int8_t direction = 5;
    
    OLED_Clear_Display();
    
    // In chữ MONITORING... và PRESS POWER TO EXIT
    OLED_PrintCenter("MONITORING...", 16);
    OLED_PrintCenter("PRESS MONITER TO EXIT", 50);
    
    // Vẽ khung thanh tiến trình ở giữa
    uint8_t bar_x = 14;
    uint8_t bar_y = 30;
    uint8_t bar_w = 100;
    uint8_t bar_h = 10;
    uint8_t fill_w = 20;
    
    for (uint8_t i = bar_x; i < bar_x + bar_w; i++) {
        OLED_DrawPixel(i, bar_y, true);
        OLED_DrawPixel(i, bar_y + bar_h - 1, true);
    }
    for (uint8_t i = bar_y; i < bar_y + bar_h; i++) {
        OLED_DrawPixel(bar_x, i, true);
        OLED_DrawPixel(bar_x + bar_w - 1, i, true);
    }
    
    // Vẽ khối bên trong chạy qua lại
    for (uint8_t i = bar_x + 2 + fill_pos; i < bar_x + 2 + fill_pos + fill_w; i++) {
        for (uint8_t j = bar_y + 2; j < bar_y + bar_h - 2; j++) {
            OLED_DrawPixel(i, j, true);
        }
    }
    
    OLED_UpdateScreen();
    
    // Cập nhật vị trí cho frame tiếp theo
    fill_pos += direction;
    if (fill_pos >= (bar_w - 4 - fill_w)) {
        fill_pos = bar_w - 4 - fill_w;
        direction = -5;
    } else if (fill_pos <= 0) {
        fill_pos = 0;
        direction = 5;
    }
}

